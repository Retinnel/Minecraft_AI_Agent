"""Приведение русского текста к виду, пригодному для сопоставления.

Запрос игрока и название предмета в базе знаний почти никогда не совпадают дословно:
«мне бы 10 наковален» и «Наковальня» — это одно и то же, но ни как строки, ни как наборы
слов они не равны. Поэтому обе стороны приводятся к основам слов, и сравниваются уже они.

Морфология здесь покрывается правилами лишь частично: стеммер обрезает окончания, но не
знает беглых гласных («наковален» → «наковал» против «наковальня» → «наковальн»). Остаток
закрывается нечётким сравнением основ в lexical.py и векторным сопоставлением, для которого
лексический слой служит быстрым и объяснимым первым приближением.
"""

from __future__ import annotations

import re
from functools import lru_cache
from typing import List, Tuple

import snowballstemmer

_stemmer = snowballstemmer.stemmer("russian")

TOKEN_PATTERN = re.compile(r"[^\W\d_]+", re.UNICODE)

# Слова, не несущие сведений о том, какой предмет имеется в виду: обращения, вежливость,
# глаголы запроса. Убираются до сопоставления, иначе они разбавляют покрытие запроса.
STOPWORDS = frozenset({
    "а", "бы", "в", "весь", "вообще", "все", "давай", "для", "до", "ещё", "еще", "же", "и",
    "из", "или", "к", "как", "ли", "меня", "мне", "мной", "можно", "мог", "могу",
    "могла", "могли", "мы", "на", "надо", "не", "ну", "нужен", "нужна", "нужно", "нужны",
    "о", "он", "она", "оно", "от", "очень", "пожалуйста", "получи", "получить", "потом",
    "при", "просто", "пусть", "с", "сейчас", "себе", "так", "такой", "тебе", "ты", "у",
    "хотел", "хотела", "хотелось", "хочу", "что", "чтобы", "штук", "штуки", "штука", "я",
    # глаголы действий: намерение определяется отдельно, на резолв предмета они не влияют
    "бросай", "бросить", "выдай", "выдать", "дай", "дать", "забери", "забрать",
    "закинь", "закинуть", "заспавни", "заспавнить", "кинь", "кинуть", "отказался",
    "отказалась", "отказаться", "подкинь", "подкинуть", "скинь", "скинуть",
    "призови", "призвать", "спавн", "спавни", "создай", "создать", "убери", "убрать",
    "удали", "удалить",
    # глаголы получения: модель иногда переносит их в название вместе с предметом
    # («скрафтить факел»), и тогда половина запроса остаётся необъяснённой
    "взять", "возьми", "где", "добыть", "добудь", "достать", "достань", "изготовить",
    "изготовь", "крафт", "крафтить", "найти", "найди", "сделать", "сделай", "скрафти",
    "скрафтить", "смастерить", "собрать", "собери",
    # английские, на случай смешанного ввода
    "a", "an", "give", "get", "me", "need", "please", "some", "spawn", "summon", "the",
    "want", "you",
})

# Числительные словами: количество извлекается отдельным механизмом, здесь они мешают.
NUMERALS = frozenset({
    "один", "одна", "одно", "два", "две", "три", "четыре", "пять", "шесть", "семь",
    "восемь", "девять", "десять", "одиннадцать", "двенадцать", "двадцать", "тридцать",
    "сорок", "пятьдесят", "сто", "стек", "стека", "стеков", "пара", "пару", "немного",
})


def normalize(text: str) -> str:
    """Нижний регистр, единая «е», разделители вместо пунктуации."""
    value = (text or "").lower().replace("ё", "е")
    value = value.replace("-", " ").replace("_", " ")
    return re.sub(r"\s+", " ", value).strip()


def tokenize(text: str) -> List[str]:
    """Слова без цифр и пунктуации."""
    return TOKEN_PATTERN.findall(normalize(text))


@lru_cache(maxsize=65536)
def stem(word: str) -> str:
    return _stemmer.stemWord(word)


def name_stems(text: str) -> Tuple[str, ...]:
    """Основы названия из базы знаний: служебные слова не отбрасываются.

    Название короткое и осмысленное целиком: в «Блоке из алмаза» предлог «из» выброшен
    быть не может, иначе название перестанет отличаться от «Алмазного блока».
    """
    return tuple(stem(token) for token in tokenize(text))


def query_stems(text: str) -> Tuple[str, ...]:
    """Основы запроса игрока без служебных слов и числительных.

    Если после отсева ничего не осталось, возвращается исходный набор: запрос из одних
    служебных слов лучше сопоставить плохо, чем не сопоставить вовсе.
    """
    tokens = tokenize(text)
    filtered = [token for token in tokens if token not in STOPWORDS and token not in NUMERALS]
    return tuple(stem(token) for token in (filtered or tokens))
